/**
 * Ищет ответ по вопросу игрока. Учитывает роль игрока.
 */
export function findAnswer(question: string, role?: string, isSpy?: boolean): string | null {
  const q = question.toLowerCase().trim();
  const activeRole: RoleType = isSpy ? 'SPY' : ((role as RoleType) || 'REPORTER');

  // Сначала ищем ответы, привязанные к роли
  for (const entry of KNOWLEDGE_BASE) {
    if (entry.roles && !entry.roles.includes(activeRole)) continue;
    for (const keyword of entry.keywords) {
      if (q.includes(keyword.toLowerCase())) {
        return entry.answer;
      }
    }
  }

  // Затем — общие (без roles)
  for (const entry of KNOWLEDGE_BASE) {
    if (entry.roles) continue;
    for (const keyword of entry.keywords) {
      if (q.includes(keyword.toLowerCase())) {
        return entry.answer;
      }
    }
  }

  return null;
}

/**
 * Возвращает название помощника для роли.
 */
export function getAssistantName(role: string, isSpy: boolean): string {
  if (isSpy) return ASSISTANT_NAMES.SPY;
  return ASSISTANT_NAMES[role as RoleType] || 'Помощник';
}

/**
 * Возвращает приветствие для роли.
 */
export function getAssistantGreeting(role: string, isSpy: boolean): string {
  if (isSpy) return ASSISTANT_GREETINGS.SPY;
  return ASSISTANT_GREETINGS[role as RoleType] || ASSISTANT_GREETINGS.REPORTER;
}